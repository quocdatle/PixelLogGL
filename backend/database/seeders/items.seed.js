async function seedItems() {
  const count = await Item.countDocuments();
  if (count === SEED_ITEMS.length) {
    console.log(`[SEEDER] Đã có đủ ${count} vật phẩm trong database.`);
    return;
  }

  console.log(`[SEEDER] Đang cập nhật dữ liệu ${SEED_ITEMS.length} vật phẩm từ items.md...`);
  for (const item of SEED_ITEMS) {
    await Item.updateOne({ name: item.name }, { $set: item }, { upsert: true });
  }
  console.log(`[SEEDER] Đã đồng bộ thành công ${SEED_ITEMS.length} vật phẩm gacha!`);
}

